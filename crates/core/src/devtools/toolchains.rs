//! Rust and Python toolchain analyzers.

use super::{child_dirs, file_name_str, find_dirs_named, make_item, DevPaths};
use crate::model::*;
use std::path::Path;

fn rustup_default(home: &Path) -> Option<String> {
    let settings = std::fs::read_to_string(home.join(".rustup").join("settings.toml")).ok()?;
    for line in settings.lines() {
        let t = line.trim();
        if let Some(rest) = t.strip_prefix("default_toolchain") {
            if let Some(v) = rest.split('=').nth(1) {
                return Some(v.trim().trim_matches('"').to_string());
            }
        }
    }
    None
}

pub fn analyze_rust(paths: &DevPaths) -> Option<ToolReport> {
    let mut sections: Vec<ToolSection> = Vec::new();
    let rustup_home = paths.home.join(".rustup");
    if rustup_home.exists() {
        let default = rustup_default(&paths.home);
        let toolchains = rustup_home.join("toolchains");
        let mut items = Vec::new();
        if toolchains.exists() {
            for dir in child_dirs(&toolchains) {
                let name = file_name_str(&dir);
                let is_default = default.as_deref() == Some(name.as_str());
                items.push(make_item(
                    name.clone(),
                    &dir,
                    if is_default {
                        ToolItemState::Current
                    } else {
                        ToolItemState::Informational
                    },
                    if is_default {
                        "Default Rust toolchain."
                    } else {
                        "Installed Rust toolchain (not the default)."
                    },
                ));
            }
        }
        if !items.is_empty() {
            sections.push(ToolSection {
                title: "Rust toolchains".to_string(),
                items,
            });
        }
    }

    // target folders that belong to a Cargo project.
    let targets = find_dirs_named(&paths.scan_root, &["target"], 4);
    let project_targets: Vec<_> = targets
        .into_iter()
        .filter(|t| {
            t.parent()
                .map(|p| p.join("Cargo.toml").exists())
                .unwrap_or(false)
        })
        .collect();
    if !project_targets.is_empty() {
        let items: Vec<ToolItem> = project_targets
            .iter()
            .map(|t| {
                make_item(
                    file_name_str(t.parent().unwrap_or(t.as_path())),
                    t,
                    ToolItemState::Informational,
                    "Cargo build output for this project; regenerated by the next build.",
                )
            })
            .collect();
        sections.push(ToolSection {
            title: "Cargo target folders".to_string(),
            items,
        });
    }

    let mut caches = Vec::new();
    for (label, p) in [
        (
            "Cargo registry cache",
            paths.home.join(".cargo").join("registry"),
        ),
        ("Cargo git checkouts", paths.home.join(".cargo").join("git")),
        ("Cargo binaries", paths.home.join(".cargo").join("bin")),
    ] {
        if p.exists() {
            caches.push(make_item(
                label,
                &p,
                ToolItemState::Informational,
                "Cargo home data.",
            ));
        }
    }
    if !caches.is_empty() {
        sections.push(ToolSection {
            title: "Cargo caches".to_string(),
            items: caches,
        });
    }

    if sections.is_empty() {
        None
    } else {
        Some(ToolReport {
            tool: "Rust".to_string(),
            sections,
        })
    }
}

pub fn analyze_python(paths: &DevPaths) -> Option<ToolReport> {
    let mut sections: Vec<ToolSection> = Vec::new();
    let venvs = find_dirs_named(&paths.scan_root, &[".venv", "venv"], 4);
    if !venvs.is_empty() {
        let items: Vec<ToolItem> = venvs
            .iter()
            .map(|v| {
                let project = v.parent().unwrap_or(v.as_path());
                let has_reqs = project.join("requirements.txt").exists()
                    || project.join("pyproject.toml").exists()
                    || project.join("Pipfile").exists();
                make_item(
                    format!("{} ({})", file_name_str(project), file_name_str(v)),
                    v,
                    ToolItemState::Informational,
                    if has_reqs {
                        "Virtual environment; the project has a requirements or project file to recreate it from."
                    } else {
                        "Virtual environment; no requirements file found beside it, so recreation may be manual."
                    },
                )
            })
            .collect();
        sections.push(ToolSection {
            title: "Virtual environments".to_string(),
            items,
        });
    }

    let mut caches = Vec::new();
    for (label, p) in [
        ("pip cache", paths.local.join("pip").join("Cache")),
        (
            "pip cache (~/.cache/pip)",
            paths.home.join(".cache").join("pip"),
        ),
        ("uv cache", paths.local.join("uv").join("cache")),
        (
            "uv cache (~/.cache/uv)",
            paths.home.join(".cache").join("uv"),
        ),
        ("Poetry cache", paths.local.join("pypoetry").join("Cache")),
    ] {
        if p.exists() {
            caches.push(make_item(
                label,
                &p,
                ToolItemState::Informational,
                "Python package download cache.",
            ));
        }
    }
    if !caches.is_empty() {
        sections.push(ToolSection {
            title: "Package caches".to_string(),
            items: caches,
        });
    }

    if sections.is_empty() {
        None
    } else {
        Some(ToolReport {
            tool: "Python".to_string(),
            sections,
        })
    }
}

pub fn project_has_manifest(dir: &Path) -> bool {
    ["Cargo.toml", "package.json", "pyproject.toml"]
        .iter()
        .any(|f| dir.join(f).exists())
}
