//! .NET and IDE caches, in the same analyzer style: bin/obj per project,
//! NuGet caches, Visual Studio and JetBrains caches.

use super::{child_dirs, file_name_str, find_dirs_named, make_item, DevPaths};
use crate::model::*;
use std::path::Path;

fn has_dotnet_project(dir: &Path) -> bool {
    if let Ok(read) = std::fs::read_dir(dir) {
        for entry in read.flatten() {
            let name = entry.file_name().to_string_lossy().to_lowercase();
            if name.ends_with(".csproj") || name.ends_with(".fsproj") || name.ends_with(".sln") {
                return true;
            }
        }
    }
    false
}

pub fn analyze(paths: &DevPaths) -> Option<ToolReport> {
    let mut sections: Vec<ToolSection> = Vec::new();

    let mut build_dirs = find_dirs_named(&paths.scan_root, &["bin", "obj"], 4);
    build_dirs.retain(|d| {
        // bin/obj belong to a .NET project when the parent (or grandparent
        // for obj under a project folder) holds a project file.
        let parent = d.parent().unwrap_or(d.as_path());
        has_dotnet_project(parent) || parent.parent().map(has_dotnet_project).unwrap_or(false)
    });
    if !build_dirs.is_empty() {
        let items: Vec<ToolItem> = build_dirs
            .iter()
            .map(|d| {
                make_item(
                    format!(
                        "{} ({})",
                        file_name_str(d.parent().unwrap_or(d.as_path())),
                        file_name_str(d)
                    ),
                    d,
                    ToolItemState::Informational,
                    ".NET build output; regenerated by the next build.",
                )
            })
            .collect();
        sections.push(ToolSection {
            title: "bin / obj by project".to_string(),
            items,
        });
    }

    let mut caches = Vec::new();
    for (label, p) in [
        ("NuGet packages", paths.home.join(".nuget").join("packages")),
        (
            "NuGet HTTP cache",
            paths.local.join("NuGet").join("v3-cache"),
        ),
        ("NuGet scratch", paths.local.join("NuGet").join("scratch")),
    ] {
        if p.exists() {
            caches.push(make_item(
                label,
                &p,
                ToolItemState::Informational,
                "NuGet cache; packages are restored on demand.",
            ));
        }
    }
    let vs_root = paths.local.join("Microsoft").join("VisualStudio");
    if vs_root.exists() {
        for dir in child_dirs(&vs_root) {
            for sub in ["ComponentModelCache", "Cache"] {
                let p = dir.join(sub);
                if p.exists() {
                    caches.push(make_item(
                        format!("Visual Studio {} ({})", sub, file_name_str(&dir)),
                        &p,
                        ToolItemState::Informational,
                        "Visual Studio component/cache data.",
                    ));
                }
            }
        }
    }
    let jetbrains = paths.local.join("JetBrains");
    if jetbrains.exists() {
        for dir in child_dirs(&jetbrains) {
            for sub in ["caches", "log", "index"] {
                let p = dir.join(sub);
                if p.exists() {
                    caches.push(make_item(
                        format!("JetBrains {} ({})", sub, file_name_str(&dir)),
                        &p,
                        ToolItemState::Informational,
                        "JetBrains IDE cache; rebuilt automatically.",
                    ));
                }
            }
        }
    }
    if !caches.is_empty() {
        sections.push(ToolSection {
            title: "NuGet and IDE caches".to_string(),
            items: caches,
        });
    }

    if sections.is_empty() {
        None
    } else {
        Some(ToolReport {
            tool: ".NET".to_string(),
            sections,
        })
    }
}
